"""Fit the existing boot artwork into the OTA layout; emit flash-only A8 pixels."""
from pathlib import Path
import hashlib
import json
from PIL import Image

root = Path(__file__).resolve().parents[1]
source = root / 'assets/boot/ling-zhu-source.png'
original = Image.open(source).convert('L')
# Trim the black margin, preserving the cat, sparkle and original wordmark.
bounds = original.point(lambda p: 255 if p >= 32 else 0).getbbox()
assert bounds
art = original.crop(bounds)
width = 168
height = round(art.height * width / art.width)
assert height <= 190
art = art.resize((width, height), Image.Resampling.LANCZOS)
data = art.tobytes()
output = root / 'main/nuwax_ui_v28/assets/ota_logo.c'
output.write_text('// Generated by tools/generate-ota-logo.py; original boot artwork.\n'
    '#include "lvgl.h"\n\nstatic const uint8_t pixels[] = {\n' +
    ''.join('    ' + ','.join(f'0x{v:02x}' for v in data[i:i+24]) + ',\n'
            for i in range(0, len(data), 24)) + '};\n\n'
    'const lv_image_dsc_t nuwax_ota_logo = {\n'
    '    .header.magic = LV_IMAGE_HEADER_MAGIC,\n'
    '    .header.cf = LV_COLOR_FORMAT_A8,\n'
    f'    .header.w = {width}, .header.h = {height}, .header.stride = {width},\n'
    '    .data_size = sizeof(pixels), .data = pixels,\n};\n', encoding='utf-8')
report = dict(sourceSha256=hashlib.sha256(source.read_bytes()).hexdigest(),
              sourceBounds=bounds, width=width, height=height, bytes=len(data),
              pixelsSha256=hashlib.sha256(data).hexdigest())
(root / 'assets/boot/ota-logo-manifest.json').write_text(
    json.dumps(report, indent=2), encoding='utf-8')
print(json.dumps(report, indent=2))
