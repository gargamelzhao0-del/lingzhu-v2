"""Convert the approved PNG to bounded-row RGB565 RLE for the boot display.

No redraw or image generation: preserve the supplied square composition,
resample to 360x360 and quantize to the display's RGB565 format.
Requires Pillow; run explicitly when replacing the approved artwork.
"""
import hashlib
import json
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parents[1]
source = root / 'assets/boot/ling-zhu-source.png'
im = Image.open(source).convert('RGBA')
assert im.width == im.height, 'Approved boot art must be square'
background = Image.new('RGBA', im.size, (0, 0, 0, 255))
background.alpha_composite(im)
im = background.convert('RGB').resize((360, 360), Image.Resampling.LANCZOS)
pixels = [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
          for r, g, b in im.getdata()]
data = bytearray()
rows = [0]
for y in range(360):
    row = pixels[y * 360:(y + 1) * 360]
    x = 0
    while x < 360:
        run = 1
        while x + run < 360 and run < 255 and row[x + run] == row[x]:
            run += 1
        color = row[x]
        data.extend((run, color & 255, color >> 8))
        x += run
    rows.append(len(data))
output = root / 'main/assets/ling_zhu_boot_logo.c'
output.write_text('// Generated by tools/convert-boot-logo.py; do not edit.\n'
    '#include "ling_zhu_boot_logo.h"\n\n'
    'const uint8_t ling_zhu_boot_logo_data[] = {\n' +
    ''.join('    ' + ','.join(f'0x{v:02x}' for v in data[i:i+24]) + ',\n'
            for i in range(0, len(data), 24)) + '};\n\n'
    'const uint32_t ling_zhu_boot_logo_rows[361] = {\n' +
    ''.join('    ' + ','.join(str(v) for v in rows[i:i+12]) + ',\n'
            for i in range(0, len(rows), 12)) + '};\n'
    'const size_t ling_zhu_boot_logo_size = sizeof(ling_zhu_boot_logo_data);\n',
    encoding='utf-8')
# Preview represents the actual RGB565 output, not the high-resolution input.
preview = Image.new('RGB', (360, 360))
preview.putdata([(((v >> 11) * 255) // 31,
                  (((v >> 5) & 63) * 255) // 63, ((v & 31) * 255) // 31)
                 for v in pixels])
preview.save(source.parent / 'ling-zhu-360.png')
raw = b''.join(v.to_bytes(2, 'little') for v in pixels)
(source.parent / 'ling-zhu-360.rgb565').write_bytes(raw)
report = dict(width=360, height=360, sourceSha256=hashlib.sha256(source.read_bytes()).hexdigest(),
              rgb565Sha256=hashlib.sha256(raw).hexdigest(),
              sourceCsha256=hashlib.sha256(output.read_bytes()).hexdigest(),
              rleBytes=len(data), rowIndexBytes=len(rows)*4)
(source.parent / 'manifest.json').write_text(json.dumps(report, indent=2), encoding='utf-8')
print(json.dumps(report, indent=2))
