"""Reproduce the approved round 1% warning using small, flash-only LVGL assets.

Source glyph subset and SIL OFL are in assets/fonts/low-battery. Requires Pillow.
No runtime font loading, screen-sized image, or dependency on the emotion pack.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
from ui_asset_codec import byte_array, emit_frames

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / 'assets/fonts/low-battery/ResourceHanRounded-preview-subset.otf'
SCALE = 4

def font(size, weight, scale=SCALE):
    result = ImageFont.truetype(str(FONT), size * scale)
    result.set_variation_by_axes([weight, 40])
    return result

def array(data):
    return '\n'.join(','.join(str(v) for v in data[i:i+24]) + ','
                     for i in range(0, len(data), 24))

def make_font(name, text, size, height, weight):
    face = font(size, weight)
    chars = sorted(set(text), key=ord)
    bitmap = bytearray()
    glyphs = ['{0}']
    for char in chars:
        width = max(1, round(face.getlength(char) / SCALE))
        im = Image.new('L', (width*SCALE, height*SCALE))
        ImageDraw.Draw(im).text((0, (height-4)*SCALE), char, font=face,
                               fill=255, anchor='ls')
        pixels = [round(v*15/255) for v in im.resize(
            (width, height), Image.Resampling.LANCZOS).tobytes()]
        glyphs.append(f'{{.bitmap_index={len(bitmap)},.adv_w={width*16},'
                      f'.box_w={width},.box_h={height}}}')
        if len(pixels) % 2: pixels.append(0)
        bitmap.extend((pixels[i]<<4)|pixels[i+1] for i in range(0,len(pixels),2))
    base = ord(chars[0])
    return (f'static const uint8_t {name}_bitmap[]={{\n{array(bitmap)}\n}};\n'
            f'static const lv_font_fmt_txt_glyph_dsc_t {name}_glyphs[]={{'+','.join(glyphs)+'};\n'
            f'static const uint16_t {name}_unicode[]={{'+','.join(str(ord(c)-base) for c in chars)+'};\n'
            f'static const lv_font_fmt_txt_cmap_t {name}_maps[]={{{{.range_start={base},'
            f'.range_length={ord(chars[-1])-base+1},.glyph_id_start=1,.unicode_list={name}_unicode,'
            f'.list_length={len(chars)},.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}}};\n'
            f'static const lv_font_fmt_txt_dsc_t {name}_dsc={{.glyph_bitmap={name}_bitmap,'
            f'.glyph_dsc={name}_glyphs,.cmaps={name}_maps,.cmap_num=1,.bpp=4}};\n'
            f'const lv_font_t {name}={{.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,'
            '.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,'
            f'.line_height={height},.base_line=0,.dsc=&{name}_dsc}};\n')

out = ['/* Generated by tools/generate-low-battery-assets.py; glyphs: SIL OFL 1.1. */\n#include "low_battery_assets.h"\n']
out.append(make_font('nuwax_font_low_battery_22', '电量不足', 22, 32, 500))
out.append(make_font('nuwax_font_low_battery_14', '即将关机，请连接充电器', 14, 22, 400))
# Bake subpixel geometry once at 8x resolution. Runtime blends adjacent masks
# in one 8112-byte buffer instead of LVGL's 1/256 integer-scale jumps.
ICON_SCALE = 8
im = Image.new('L', (96*ICON_SCALE, 70*ICON_SCALE))
d = ImageDraw.Draw(im)
box = lambda a: tuple(x*ICON_SCALE for x in a)
d.rounded_rectangle(box((5,9,75,61)), radius=16*ICON_SCALE, outline=255, width=6*ICON_SCALE)
d.rounded_rectangle(box((85,24,91,46)), radius=3*ICON_SCALE, fill=255)
d.rounded_rectangle(box((21,24,27,46)), radius=3*ICON_SCALE, fill=255)
d.text((52*ICON_SCALE,35*ICON_SCALE), '1%', font=font(18,500,ICON_SCALE), anchor='mm', fill=255)
frames=[]
for i in range(17):
    scale = 1.0 + 0.04*i/16
    # Both source and destination retain the same optical centre for every frame.
    transform=(1/scale,0,(48-52/scale)*ICON_SCALE,
               0,1/scale,(35-39/scale)*ICON_SCALE)
    frame=im.transform((104*ICON_SCALE,78*ICON_SCALE),Image.Transform.AFFINE,
                       transform,resample=Image.Resampling.BICUBIC).resize(
                           (104,78),Image.Resampling.LANCZOS)
    frames.append(frame.tobytes())
out.append(byte_array('nuwax_low_battery_static_mask',frames[0]))
out.append(emit_frames('nuwax_low_battery_frames',frames,linkage='const'))
out.append('const lv_image_dsc_t nuwax_low_battery_icon={'
           '.header.magic=LV_IMAGE_HEADER_MAGIC,.header.cf=LV_COLOR_FORMAT_A8,'
           '.header.w=NUWAX_LOW_BATTERY_ICON_WIDTH,.header.h=NUWAX_LOW_BATTERY_ICON_HEIGHT,'
           '.header.stride=NUWAX_LOW_BATTERY_ICON_WIDTH,'
           '.data_size=NUWAX_LOW_BATTERY_ICON_BYTES,.data=nuwax_low_battery_static_mask};\n')
(ROOT/'main/nuwax_ui_v28/assets/low_battery_assets.c').write_text(''.join(out),encoding='utf-8')
print('Low battery: 17 lossless RLE masks, 104x78, 100..104%; raw static fallback; unchanged fonts')
