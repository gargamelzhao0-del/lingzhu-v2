"""Generate only the glyphs used by the OTA capsule, leaving other UI fonts intact."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
font = ImageFont.truetype(str(root/'lib/lvgl/scripts/built_in_font/SourceHanSansSC-Normal.otf'), 64)
chars = sorted(set('更新中0123456789%'), key=ord)
bitmap = bytearray()
glyphs = ['{0}']
for char in chars:
    w = max(1, round(font.getlength(char)/4))
    im = Image.new('L', (w*4, 20*4))
    ImageDraw.Draw(im).text((0, 17*4), char, font=font, fill=255, anchor='ls', stroke_width=2)
    pixels = [round(v*15/255) for v in im.resize((w, 20), Image.Resampling.LANCZOS).tobytes()]
    glyphs.append(f'{{.bitmap_index={len(bitmap)},.adv_w={w*16},.box_w={w},.box_h=20}}')
    if len(pixels)%2: pixels.append(0)
    bitmap.extend((pixels[i]<<4)|pixels[i+1] for i in range(0, len(pixels), 2))
base = ord(chars[0])
out = ['/* Generated by tools/generate-ota-font.py. */\n#include "lvgl.h"\n',
       'static const uint8_t bitmap[]={\n' + '\n'.join(','.join(str(x) for x in bitmap[i:i+24])+',' for i in range(0,len(bitmap),24))+'\n};\n',
       'static const lv_font_fmt_txt_glyph_dsc_t glyphs[]={'+','.join(glyphs)+'};\n',
       'static const uint16_t unicode_list[]={'+','.join(str(ord(c)-base) for c in chars)+'};\n',
       f'static const lv_font_fmt_txt_cmap_t maps[]={{{{.range_start={base},.range_length={ord(chars[-1])-base+1},.glyph_id_start=1,.unicode_list=unicode_list,.list_length={len(chars)},.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}}};\n',
       'static const lv_font_fmt_txt_dsc_t dsc={.glyph_bitmap=bitmap,.glyph_dsc=glyphs,.cmaps=maps,.cmap_num=1,.bpp=4};\n',
       'const lv_font_t nuwax_font_ota_16={.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height=20,.base_line=0,.dsc=&dsc};\n']
(root/'main/nuwax_ui_v28/assets/fonts/nuwax_font_ota.c').write_text(''.join(out), encoding='utf-8')
print('OTA font generated', len(chars), 'glyphs', len(bitmap), 'bitmap bytes')
