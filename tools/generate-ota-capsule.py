"""Generate flash-only A8 coverage for the code-native OTA border and icon.

8x8 area samples smooth subpixel strokes without runtime supersampling.
Union the icon strokes before filtering to avoid double-blended joins.
"""
from pathlib import Path
from math import hypot

root = Path(__file__).resolve().parents[1]
width, height, samples = 224, 52, 8
border = 1.75
icon_radius = 1.75
strokes = ((33,12,33,24), (28,20,33,25), (33,25,38,20),
           (24,26,24,31), (24,31,42,31), (42,31,42,26))

def covered(x, y):
    distance = hypot(x - min(max(x,26),width-26), y-26)
    if 26-border <= distance <= 26:
        return True
    if not (22 <= x <= 44 and 10 <= y <= 33):
        return False
    for ax, ay, bx, by in strokes:
        dx, dy = bx-ax, by-ay
        t = min(1, max(0, ((x-ax)*dx+(y-ay)*dy)/(dx*dx+dy*dy)))
        if hypot(x-ax-t*dx, y-ay-t*dy) <= icon_radius:
            return True
    return False

pixels = bytes(round(255*sum(covered(x+(sx+.5)/samples,y+(sy+.5)/samples)
    for sy in range(samples) for sx in range(samples))/(samples*samples))
    for y in range(height) for x in range(width))
output = root/'main/nuwax_ui_v28/assets/ota_capsule.c'
output.write_text('// Generated by tools/generate-ota-capsule.py; flash-only A8 coverage.\n'
    '#include "lvgl.h"\n\nstatic const uint8_t pixels[] = {\n' +
    ''.join('    '+','.join(f'0x{v:02x}' for v in pixels[i:i+24])+',\n'
            for i in range(0,len(pixels),24)) + '};\n\n'
    'const lv_image_dsc_t nuwax_ota_capsule = {\n'
    '    .header.magic = LV_IMAGE_HEADER_MAGIC,\n'
    '    .header.cf = LV_COLOR_FORMAT_A8,\n'
    f'    .header.w = {width}, .header.h = {height}, .header.stride = {width},\n'
    '    .data_size = sizeof(pixels), .data = pixels,\n};\n',encoding='utf-8')
print(f'OTA capsule: {width}x{height}, {len(pixels)} flash bytes, '
      f'{border}px border, {icon_radius*2}px icon, {samples}x{samples} coverage')
