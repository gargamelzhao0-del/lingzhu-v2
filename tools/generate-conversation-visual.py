"""Generate small antialiased masks; firmware performs only bounded copies."""
from pathlib import Path
from PIL import Image, ImageDraw
from ui_asset_codec import emit_frames
import math

ROOT = Path(__file__).resolve().parents[1]
S = 4
W, H, N = 44, 24, 24
BAR_FRAMES = 60  # 3 seconds at 20 FPS; ripple timing remains unchanged.

def mask(w, h, paint):
    im = Image.new('L', (w*S, h*S))
    paint(ImageDraw.Draw(im))
    return list(im.resize((w, h), Image.Resampling.LANCZOS).tobytes())

def line(d, points, width, value=255):
    pts = [(round(x*S), round(y*S)) for x,y in points]
    d.line(pts, fill=value, width=round(width*S), joint='curve')
    r = width*S/2
    for x,y in (pts[0], pts[-1]):
        d.ellipse((x-r,y-r,x+r,y+r), fill=value)

def ripple(d, frame):
    for offset in (0, N//2):
        p = ((frame+offset)%N)/N
        # Fuller capsule strokes, close to the speaking bars' 4px width.
        # Reduce travel slightly so thicker arcs keep the existing footprint.
        radius = 7+9.2*p
        alpha = round(235*(1-p)**0.7)
        for side in (-1,1):
            pts = [(22+side*radius*math.cos(t),12+radius*math.sin(t))
                   for t in [(-0.50+i*1.0/24) for i in range(25)]]
            line(d,pts,3.6,alpha)
    d.ellipse((20*S,10*S,24*S,14*S),fill=255)

def bars(d, frame):
    for i,x in enumerate((15,22,29)):
        # Sample one periodic curve without duplicating its endpoint. Heights
        # and velocity remain continuous across the last -> first frame.
        h=7+8*(0.5+0.5*math.sin(2*math.pi*frame/BAR_FRAMES+i*1.7))
        d.rounded_rectangle(((x-2)*S,(12-h/2)*S,(x+2)*S,(12+h/2)*S),radius=2*S,fill=255)

def emit(name, data, width):
    return emit_frames(name,data)

text='/* Generated by tools/generate-conversation-visual.py. */\n#pragma once\n#include "../assets/asset_rle.h"\n'
text+=emit('conversation_ripple', [mask(W,H,lambda d,f=f:ripple(d,f)) for f in range(N)],W)
text+=emit('conversation_bars', [mask(W,H,lambda d,f=f:bars(d,f)) for f in range(BAR_FRAMES)],W)
out=ROOT/'main/nuwax_ui_v28/face/conversation_visual_assets.h'
out.write_text(text,encoding='utf-8')
print(out)
